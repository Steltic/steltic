"""Build a user-designed building in build-only mode.

build(job_dir, desc, answers) writes into job_dir:
    building_description.json   the description with the answers applied (what HR built from)
    answers.json                the user's answers / accepted defaults
    missing_items.json          what is still open (always written; "ready": true when nothing is)
and, only when nothing key / default / refused is open:
    cfg.py                      generated by translate.cfg_text (do not edit)
    provenance.json             the source of every cfg value, the derived rules, the accepted defaults
    model_opensees.py, model_static.py, report.html, design/*  -- the normal HR pipeline
The pipeline runs in a child process (the engine keeps module-level state). Member D/C ratios are NOT computed:
the HR engine has no coded capacities (the design agent supplies them in a normal run) and a user design is not
checked by Steltic HR; calc_package.json says so on every member.
"""
from __future__ import annotations

import hashlib
import json
import os
import pathlib
import subprocess
import sys
import time

from . import schema as S
from . import translate as TR

ENGINE_DIR = pathlib.Path(os.environ.get("STELTIC_ENGINE_DIR") or (pathlib.Path(__file__).resolve().parents[2] / "steel_engine"))
NOT_CHECKED = ("not computed -- build-only: the user's own design, modelled as given; member strengths are not "
               "checked by Steltic HR (see the NL DDM for a design check by advanced analysis)")

_PIPE = r'''
import json, os, runpy, sys, traceback
name = sys.argv[1]
ns = runpy.run_path("cfg.py")
cfg = ns["cfg"]
import pipeline, consistency, report
out = pipeline.design_and_report(name, cfg)
try:
    consistency.check(name)
except Exception as ex:
    print("[build_only] consistency.check failed: %s" % ex)
print("[build_only] pipeline done")
'''

_POST = r'''
import sys
name = sys.argv[1]
import report
report.build_report(name)
print("[build_only] report re-rendered")
'''


def _dump(p, obj):
    p.write_text(json.dumps(obj, indent=1, default=str), encoding="utf-8")


def _run_engine(job_dir: pathlib.Path, code: str, name: str, python=None, timeout=None, log=None):
    timeout = timeout or int(os.environ.get("BUILD_ONLY_TIMEOUT", "7200"))      # large buildings take a while
    env = {**os.environ, "PYTHONPATH": str(ENGINE_DIR), "MPLBACKEND": "Agg", "PYTHONUTF8": "1",
           "PYTHONIOENCODING": "utf-8", "STEEL_BUILDER_JOBS": str(job_dir.parent), "PYTHONDONTWRITEBYTECODE": "1"}
    script = job_dir / ".run" / "_build_only.py"
    script.parent.mkdir(parents=True, exist_ok=True)
    script.write_text(code, encoding="utf-8")
    p = subprocess.run([python or sys.executable, str(script), name], cwd=str(job_dir), env=env, capture_output=True,
                       text=True, encoding="utf-8", errors="replace", timeout=timeout)
    if log is not None:
        with open(log, "a", encoding="utf-8") as f:
            f.write(p.stdout or "")
            f.write(p.stderr or "")
    return p


def _postprocess_calc(job_dir: pathlib.Path, desc: dict, T: dict, prov: dict):
    """Record the user's design data the NL engines read from calc_package.json (RBS cuts, Lb, doublers, the
    system) and mark every member as not checked. Demands written by the pipeline are kept."""
    p = job_dir / "design" / "calc_package.json"
    if not p.exists():
        return None
    calc = json.loads(p.read_text(encoding="utf-8"))
    rbs = T["rbs_by_sec"]
    Lb = {S.norm_section(k): float(v) for k, v in ((desc.get("details") or {}).get("beam_Lb_in") or {}).items() if S.norm_section(k)}
    for m in calc.get("members") or []:
        inp = m.setdefault("inputs", {})
        sec = S.norm_section(inp.get("section"))
        if sec in rbs:
            inp["RBS"] = {k: rbs[sec][k] for k in ("a_in", "b_in", "c_in")}
        if sec in Lb:
            inp["Lb_in"] = Lb[sec]
        for k in ("limit_state", "capacity", "DC"):
            m.setdefault(k, None)
        m["cited"] = None
        m["build_only"] = NOT_CHECKED
    for c in calc.get("connections") or []:
        if isinstance(c, dict):
            c["build_only"] = NOT_CHECKED
    cd = calc.setdefault("capacity_design", {})
    se = desc["seismic"]
    sysd = se.get("system") or {}
    cd["system"] = "user-designed (build-only): X %s, Y %s; R/Cd/Omega0 X %s/%s/%s, Y %s/%s/%s" % (
        sysd.get("X"), sysd.get("Y"), *[(se.get(f) or {}).get(d) for d in ("X",) for f in ("R", "Cd", "Om0")],
        *[(se.get(f) or {}).get(d) for d in ("Y",) for f in ("R", "Cd", "Om0")])
    cd["build_only"] = True
    bb = (desc.get("details") or {}).get("beam_bracing_in")
    if bb:
        cd["beam_bracing"] = {"Lb_provided_in": float(bb), "source": "building description (details.beam_bracing_in)"}
    dbl = (desc.get("details") or {}).get("doublers") or []
    if dbl:
        G = S.Geometry(desc)
        lidx = {n: k for k, (n, _) in enumerate(G.levels)}
        by_joint = []
        for d in dbl:
            xy = G.xy(d); k = lidx.get(str(d.get("level")))
            if xy is None or k is None:
                continue
            x_in, y_in = round(xy[0] * TR.FT, 3), round(xy[1] * TR.FT, 3)
            tag = next((t for t, (x, y, z) in T["nodes"].items() if t // 100000 == k and abs(x - (x_in - T["xs"][0] * TR.FT)) < 1e-3
                        and abs(y - (y_in - T["ys"][0] * TR.FT)) < 1e-3), None)
            colsec = next((c[3] for c in T["COLS"] if tag in (c[1], c[2])), None)
            bms = [b[3] for b in T["BEAMS"] if tag in (b[1], b[2]) and b[4] in ("none",) + (("J",) if b[1] == tag else ("I",))]
            by_joint.append(dict(joint="user doubler %s/%s L%d" % (d.get("x"), d.get("y"), k), level=k, column=colsec,
                                 beams=" + ".join(bms), doubler_in=float(d["t_in"]), source="building description"))
        cd["panel_zone"] = dict(by_joint=by_joint, source="user-designed building: doublers as given")
    elif (desc.get("details") or {}).get("doublers") == []:
        cd["panel_zone"] = dict(by_joint=[], source="user-designed building: no doubler plates (accepted)")
    calc["build_only"] = dict(note=NOT_CHECKED, provenance="provenance.json")
    _dump(p, calc)
    return calc


def build(job_dir, desc: dict, answers: dict | None = None, name: str | None = None, python=None, run_pipeline=True,
          log=None) -> dict:
    job_dir = pathlib.Path(job_dir)
    job_dir.mkdir(parents=True, exist_ok=True)
    name = name or job_dir.name
    log = log or (job_dir / "build_only.log")
    answers = dict(answers or {})
    prev = job_dir / "answers.json"
    if prev.exists() and not answers:
        try:
            answers = json.loads(prev.read_text(encoding="utf-8"))
        except ValueError:
            answers = {}
    d = S.apply_answers(desc, answers)
    _dump(job_dir / "answers.json", answers)
    _dump(job_dir / "building_description.json", d)
    mi = S.missing_items_doc(d, name)
    _dump(job_dir / "missing_items.json", mi)
    if not mi["ready"]:
        return dict(status="needs_input", building=name, counts=mi["counts"], missing_items=mi)
    text, prov = TR.cfg_text(d, name)
    (job_dir / "cfg.py").write_text(text, encoding="utf-8")
    T = TR.build_tables(d)
    prov["built_at"] = time.strftime("%Y-%m-%d %H:%M:%S")
    _dump(job_dir / "provenance.json", prov)
    if not run_pipeline:
        return dict(status="translated", building=name, provenance=prov)
    t0 = time.time()
    p = _run_engine(job_dir, _PIPE, name, python=python, log=log)
    res = dict(building=name, returncode=p.returncode, seconds=round(time.time() - t0, 1))
    if p.returncode != 0:
        tail = "\n".join(((p.stderr or "") + (p.stdout or "")).strip().splitlines()[-25:])
        res.update(status="build_failed", error=tail)
        prov["pipeline"] = res
        _dump(job_dir / "provenance.json", prov)
        return res
    _postprocess_calc(job_dir, d, T, prov)
    _run_engine(job_dir, _POST, name, python=python, log=log)
    pr = {}
    try:
        pr = json.loads((job_dir / "design" / "pipeline_results.json").read_text(encoding="utf-8"))
    except (OSError, ValueError):
        pass
    checks = pr.get("checks") or {}
    summ = pr.get("summary") or {}
    pf_err = [x for x in (pr.get("preflight") or []) if x and x[0] == "ERROR"]
    res.update(status="built", model_declared=checks.get("model_declared"), model_consistent=checks.get("model_consistent"),
               failed_checks=pr.get("failed") or [], preflight_errors=pf_err,
               summary={k: summ.get(k) for k in ("T", "V", "W")})
    prov["pipeline"] = res
    prov["cfg_sha256"] = hashlib.sha256((job_dir / "cfg.py").read_bytes()).hexdigest()
    _dump(job_dir / "provenance.json", prov)
    return res


def gate(job_dir) -> list:
    """Build-only completion gate: problems that must stop a user-designed package (empty = pass).
    * cfg.py must be the one the translator generated (provenance cfg_sha256) -- nobody resized anything;
    * the model must be built as declared (model_declared, model_consistent);
    * nothing may be open in missing_items.json.
    Code limits (drift, D/C) are reported, never enforced, for a user design."""
    job_dir = pathlib.Path(job_dir)
    probs = []
    try:
        prov = json.loads((job_dir / "provenance.json").read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return ["provenance.json missing: not a build-only package"]
    cfg = job_dir / "cfg.py"
    if not cfg.exists():
        probs.append("cfg.py missing")
    elif hashlib.sha256(cfg.read_bytes()).hexdigest() != prov.get("cfg_sha256"):
        probs.append("cfg.py differs from the one generated from the user's design (provenance.json cfg_sha256): a "
                     "user-designed building is never redesigned -- regenerate it with build_only.build")
    try:
        mi = json.loads((job_dir / "missing_items.json").read_text(encoding="utf-8"))
        if not mi.get("ready"):
            probs.append("missing_items.json still has open items: %s" % mi.get("counts"))
    except (OSError, ValueError):
        probs.append("missing_items.json missing")
    try:
        pr = json.loads((job_dir / "design" / "pipeline_results.json").read_text(encoding="utf-8"))
        ch = pr.get("checks") or {}
        for k in ("model_declared", "model_consistent"):
            if ch.get(k) is False:
                probs.append("%s failed: the model is not built as the description declares" % k)
        if pr.get("cfg_sha256") and pr["cfg_sha256"] != prov.get("cfg_sha256"):
            probs.append("design/pipeline_results.json was produced from a different cfg.py")
    except (OSError, ValueError):
        probs.append("design/pipeline_results.json missing: the pipeline has not run")
    return probs


def is_build_only(job_dir) -> bool:
    p = pathlib.Path(job_dir) / "provenance.json"
    if not p.exists():
        return False
    try:
        return json.loads(p.read_text(encoding="utf-8")).get("schema") == "steltic.provenance"
    except (OSError, ValueError):
        return False
